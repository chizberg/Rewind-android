/**
 * sRGB <-> CIE L*a*b*, the standard formulas with the constants as OpenCV spells them, because
 * every reference number the pipeline is checked against was produced by cv2.cvtColor. Port of
 * iOS `Lab`.
 * https://docs.opencv.org/4.x/de/d25/imgproc_color_conversions.html (RGB <-> CIE L*a*b*)
 */
object Lab {
    fun lightness(rgb: RGBPlanes): FloatPlane =
        FloatPlane(
            rgb.size,
            FloatArray(rgb.size.pixelCount) { i -> lightness(rgb.r[i], rgb.g[i], rgb.b[i]) },
        )

    /** L of a gray frame, the input ECCV16 takes instead of an image. The reference converts the
     *  squashed gray bytes with skimage's rgb2lab, which agrees with OpenCV's L for R = G = B. */
    fun lightnessOfGray(gray: GrayPlane): FloatPlane =
        gray.mapToFloat { byte ->
            val value = byte / BYTE_MAX
            lightness(value, value, value)
        }

    fun neutralGray(lightness: FloatPlane): GrayPlane =
        lightness.mapToGray {
            ColorizationHelpers.byte(neutralGray(it))
        }

    /**
     * The colorized photo: every pixel's L from the photo and ab from the model, through XYZ back
     * to sRGB with OpenCV's matrix. Like cv2's float COLOR_Lab2RGB, the linear channels are
     * clamped to 0...1 before the transfer function, so a color outside sRGB loses the excess.
     * https://docs.opencv.org/4.x/de/d25/imgproc_color_conversions.html#color_convert_rgb_xyz
     */
    @Suppress("MagicNumber") // OpenCV's XYZ -> sRGB matrix, element by element.
    fun rgb(
        lightness: FloatPlane,
        ab: ABPlanes,
    ): RGBPlanes {
        require(lightness.size == ab.size)
        val count = lightness.size.pixelCount
        val r = FloatArray(count)
        val g = FloatArray(count)
        val b = FloatArray(count)
        for (i in 0 until count) {
            val fy = fOfLuminance(lightness.values[i])
            val x = WHITE_X * fInverse(fy + ab.a[i] / 500)
            val y = fInverse(fy)
            val z = WHITE_Z * fInverse(fy - ab.b[i] / 200)
            r[i] = gammaEncode((3.240479f * x - 1.53715f * y - 0.498535f * z).coerceIn(0f, 1f))
            g[i] = gammaEncode((-0.969256f * x + 1.875991f * y + 0.041556f * z).coerceIn(0f, 1f))
            b[i] = gammaEncode((0.055648f * x - 0.204043f * y + 1.057311f * z).coerceIn(0f, 1f))
        }
        return RGBPlanes(lightness.size, r, g, b)
    }

    // CIE Lab replaces the cube root below (6/29)³ with a straight line that meets it in value and
    // slope: (1/3)(29/6)² t + 4/29.
    private const val THRESHOLD = 0.008856f
    private const val SLOPE = 7.787f
    private const val OFFSET = 16f / 116f

    // OpenCV's D65 white, Xn and Zn: Lab holds X and Z relative to white. Yn is 1.
    private const val WHITE_X = 0.950456f
    private const val WHITE_Z = 1.088754f

    /** Y of CIE XYZ: the Y row of the sRGB -> XYZ matrix for D65. */
    @Suppress("MagicNumber")
    private fun luminance(
        r: Float,
        g: Float,
        b: Float,
    ): Float = 0.212671f * gammaDecode(r) + 0.715160f * gammaDecode(g) + 0.072169f * gammaDecode(b)

    /** L* = 116 f(Y/Yn) - 16, scaled so black is 0 and white is 100. */
    @Suppress("MagicNumber")
    private fun lightness(
        r: Float,
        g: Float,
        b: Float,
    ): Float = 116 * f(luminance(r, g, b)) - 16

    /** L* = 116 f(Y/Yn) - 16 solved for f(Y/Yn). */
    @Suppress("MagicNumber")
    private fun fOfLuminance(lightness: Float): Float = (lightness + 16) / 116

    private fun f(t: Float): Float = if (t > THRESHOLD) cbrt(t) else SLOPE * t + OFFSET

    /** With a = b = 0 the three channels of Lab -> RGB come out equal. */
    private fun neutralGray(lightness: Float): Float =
        gammaEncode(fInverse(fOfLuminance(lightness)))

    private fun fInverse(u: Float): Float {
        val cubed = u * u * u
        return if (cubed > THRESHOLD) cubed else (u - OFFSET) / SLOPE
    }

    /** The inverse of the sRGB transfer function (IEC 61966-2-1). */
    @Suppress("MagicNumber")
    private fun gammaDecode(c: Float): Float {
        if (c <= 0.04045f) return c / 12.92f
        return ((c + 0.055f) / 1.055f).pow(2.4f)
    }

    /** The sRGB transfer function itself (IEC 61966-2-1). */
    @Suppress("MagicNumber")
    private fun gammaEncode(c: Float): Float {
        if (c <= 0.0031308f) return 12.92f * c
        return 1.055f * c.pow(1 / 2.4f) - 0.055f
    }

